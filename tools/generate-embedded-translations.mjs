import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configSource = readFileSync(join(root, "src", "config.ts"), "utf8");
const relativeFiles = Array.from(
    configSource.matchAll(/"([^"\r\n]+\/zh_Hant\.json)"/g),
    match => match[1]
);
// No vendored fallback copies on purpose.  There used to be two (dist/translation-upstream
// and upstream-translation); falling back to one silently embeds stale translations —
// you edit the real repo, build, and ship the old data with no error anywhere.
// Better to throw than to guess: point DOTABYSS_TRANSLATIONS somewhere if the sibling
// checkout is not where this expects it.
const REPO_DIR = "dotabyss-translation-client-version-s88037zz";
const candidates = [
    process.env.DOTABYSS_TRANSLATIONS && resolve(process.env.DOTABYSS_TRANSLATIONS),
    join(root, "..", "..", "Dot-abyess-Lienchu-version", REPO_DIR)
].filter(Boolean);

const translationRoot = candidates.find(dir => existsSync(join(dir, "static", "zh_Hant.json")));
if (!translationRoot) {
    throw new Error(`No translation source found. Tried:\n  ${candidates.join("\n  ")}`);
}
// Always say which one, so a wrong source is visible in the build log.
console.log(`translation source: ${resolve(translationRoot)}`);

if (relativeFiles.length === 0) {
    throw new Error("No translation files found in src/config.ts");
}

// Story and home-screen text is drawn one character per TMP_Text, so every single
// character of an already-translated line comes back through set_text on its own.
// A one-character key in the dictionary matches it, and if its value is longer the
// one-character cell wraps: 杖 -> 法杖 renders as 法 floating above the gap and 杖
// below it.  index.ts suppresses those at runtime (see translateSingleChar), but a
// *new* one arriving from masterdata must not be something we only find out about
// from a screenshot -- so name them here, every build, with how much story text
// they would have hit.  See NOTES.md section 4.3.
const singleCharKeys = new Map();
const storyText = [];
function collect(value) {
    if (!value || typeof value !== "object") return;
    for (const [key, child] of Object.entries(value)) {
        if (typeof child === "string") {
            if (child.length > 0 && key.length === 1 && child.length !== 1) singleCharKeys.set(key, child);
        } else {
            collect(child);
        }
    }
}
function collectStory(value) {
    if (!value || typeof value !== "object") return;
    for (const child of Object.values(value)) {
        if (typeof child === "string") storyText.push(child);
        else collectStory(child);
    }
}

const entries = relativeFiles.map(relative => {
    const raw = readFileSync(join(translationRoot, ...relative.split("/")), "utf8");
    const parsed = JSON.parse(raw);
    collect(parsed);
    if (relative.startsWith("novels_")) collectStory(parsed);
    return `    [${JSON.stringify(relative)}, ${JSON.stringify(raw)}]`;
});

if (singleCharKeys.size > 0) {
    const joined = storyText.join("\n");
    const rows = Array.from(singleCharKeys, ([key, value]) => [key, value, joined.split(key).length - 1])
        .sort((a, b) => b[2] - a[2]);
    console.log(`single-char keys suppressed at runtime (${rows.length}) -- these would stack inside story text:`);
    for (const [key, value, hits] of rows) {
        console.log(`  ${key} -> ${value}   ${hits} occurrence(s) in embedded story text`);
    }
}

const generated = [
    "// Generated by tools/generate-embedded-translations.mjs. Do not edit by hand.",
    "export const embeddedTranslationJson: ReadonlyArray<readonly [string, string]> = [",
    entries.join(",\n"),
    "];",
    ""
].join("\n");

writeFileSync(join(root, "src", "embedded-translations.ts"), generated, "utf8");
console.log(`embedded ${relativeFiles.length} translation files (${generated.length} source chars)`);
