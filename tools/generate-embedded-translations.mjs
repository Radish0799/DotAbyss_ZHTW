import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configSource = readFileSync(join(root, "src", "config.ts"), "utf8");
const relativeFiles = Array.from(
    configSource.matchAll(/"([^"\r\n]+\/zh_Hant\.json)"/g),
    match => match[1]
);
// No vendored fallback copies on purpose.  There used to be two (dist/translation-upstream
// and upstream-translation); falling back to one silently embeds stale translations —
// you edit the real repo, build, and ship the old data with no error anywhere.
// Better to throw than to guess: point DOTABYSS_TRANSLATIONS somewhere if the sibling
// checkout is not where this expects it.
const REPO_DIR = "dotabyss-translation-client-version-s88037zz";
const candidates = [
    process.env.DOTABYSS_TRANSLATIONS && resolve(process.env.DOTABYSS_TRANSLATIONS),
    join(root, "..", "..", "Dot-abyess-Lienchu-version", REPO_DIR)
].filter(Boolean);

const translationRoot = candidates.find(dir => existsSync(join(dir, "static", "zh_Hant.json")));
if (!translationRoot) {
    throw new Error(`No translation source found. Tried:\n  ${candidates.join("\n  ")}`);
}
// Always say which one, so a wrong source is visible in the build log.
console.log(`translation source: ${resolve(translationRoot)}`);

if (relativeFiles.length === 0) {
    throw new Error("No translation files found in src/config.ts");
}

const entries = relativeFiles.map(relative => {
    const raw = readFileSync(join(translationRoot, ...relative.split("/")), "utf8");
    JSON.parse(raw);
    return `    [${JSON.stringify(relative)}, ${JSON.stringify(raw)}]`;
});

const generated = [
    "// Generated by tools/generate-embedded-translations.mjs. Do not edit by hand.",
    "export const embeddedTranslationJson: ReadonlyArray<readonly [string, string]> = [",
    entries.join(",\n"),
    "];",
    ""
].join("\n");

writeFileSync(join(root, "src", "embedded-translations.ts"), generated, "utf8");
console.log(`embedded ${relativeFiles.length} translation files (${generated.length} source chars)`);
